// Regenerate the checked-in Unicode simple folding data; no runtime download.
import {writeFile} from 'node:fs/promises';
const source = 'https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt';
const response = await fetch(source);
if (!response.ok) throw new Error(`Unicode download failed: ${response.status}`);
const pairs = [];
for (const line of (await response.text()).split('\n')) {
  const match = /^([0-9A-F]+); [CS]; ([0-9A-F]+);/.exec(line);
  if (match) pairs.push([parseInt(match[1], 16), parseInt(match[2], 16)]);
}
const ranges = [];
for (let i = 0; i < pairs.length;) {
  const [start, target] = pairs[i];
  const delta = target - start;
  const step = i + 1 < pairs.length ? pairs[i + 1][0] - start : 1;
  let j = i + 1;
  if (step === 1 || step === 2) {
    while (j < pairs.length && pairs[j][0] - pairs[j - 1][0] === step && pairs[j][1] - pairs[j][0] === delta) j++;
  }
  ranges.push([start, pairs[j - 1][0], j === i + 1 ? 1 : step, delta]);
  i = j;
}
const code = `// Generated by scripts/generate-case-fold.mjs from Unicode 17.0.0 C + S mappings.
// ${source}
// Copyright Unicode, Inc. See ../../UNICODE-LICENSE.txt (from app/src/container).
// Each row is [first code point, last code point, stride, mapping delta].
const ranges = [
${ranges.map(row => '  [' + row.join(', ') + '],').join('\n')}
];
const folding = new Map();
for (const [first, last, step, delta] of ranges) {
  for (let point = first; point <= last; point += step) folding.set(point, point + delta);
}
export function simpleCaseFold(text) {
  let out = '';
  for (const character of text) {
    const point = character.codePointAt(0);
    out += String.fromCodePoint(folding.get(point) ?? point);
  }
  return out;
}
`;
await writeFile(new URL('../src/container/case-fold.js', import.meta.url), code);
const license = await fetch('https://www.unicode.org/license.txt');
if (!license.ok) throw new Error(`Unicode license download failed: ${license.status}`);
await writeFile(new URL('../UNICODE-LICENSE.txt', import.meta.url), await license.text());
console.log(`Generated ${pairs.length} simple folding mappings in ${ranges.length} ranges.`);
